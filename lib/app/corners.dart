/// 全应用的**圆角**只有这一份。
///
/// 改造清单 P1，需求方 2026-10-07 裁定：**只补圆角**（对齐桌面 T4
/// 「只做圆角、不做 spacing」）。字阶早归了 M3 的 `textTheme`（T7），
/// 间距**有意不做** —— 与桌面 T4 同一个理由：既不合代码、也没人执行的常量
/// 就是纯装饰。
///
/// ⚠️ **这一层的价值与桌面 T4 不一样，别照抄它的理由。** 桌面那三支是被
/// `Theme.xaml` 自己吃掉的（8 处在共享样式里、定义即使用）；这里的 `ThemeData`
/// （`main.dart`）**只吃一处**圆角 —— Chip 那支胶囊。所以这一层在手机端买的不是
/// 「主题复用」，是另外两样：
/// 1. **「这个角是干嘛的」能从名字读出来** —— 迁移前 16 处全是裸数字；
/// 2. `test/wiring_test.dart` 里的绊线能写成**零例外**（T3 裸色、T7 字号
///    都是这么收的尾，而不是挂一张白名单）。
///
/// 值是**数出来的**，不是拍的（2026-10-07 实测 `lib/` 下 17 行圆角、7 个不同数值：
/// 20×3、12×4、8×4、6×2、14×1、9×1、4×1）。所以有 4 支各只有一个用户 ——
/// 那是「改名」不是「分层」，知情接受，换来上面那两样。
///
/// ⚠️ `RoundSliderThumbShape(enabledThumbRadius: 7)`
/// （`video_player_page.dart`）**不进这里**：那是滑块拇指本身的半径，不是容器圆角。
/// 桌面 T4 排除 `ToggleSwitch` 的 `11` 同理。
abstract final class Corners {
  /// 圆头胶囊：备份页那两个状态 pill（已配对 / 未配对），以及 Chip 主题。
  static const pill = 20.0;

  /// 卡片 / 面板：提示条、抽屉里的块、设置页的块、详情页那个预览框。
  static const card = 12.0;

  /// 浅底说明块，以及录制页那颗 56×56 的【对焦】按钮。
  ///
  /// ⚠️ 那颗按钮的 `Material` 与 `InkWell` **各取一次这个值**（`recorder_view_sheets.dart`）
  /// —— 两处不同值的话，按下去的涟漪会溢到圆角外面。改这一支时两处一起改。
  static const note = 8.0;

  /// 缩略图的 `ClipRRect`。
  static const thumb = 6.0;

  /// 设置页顶那块蓝底。
  static const header = 14.0;

  /// 主色图标底那个小方块（34×34）。
  static const iconBox = 9.0;

  /// 业务类型小标 —— **列表上那个与详情页那颗共用这一支**，
  /// 两处必须是同一个值。
  ///
  /// ⚠️ **这里原本有两支。** 迁移前的现状是：列表那颗 4（padding 6/2）、
  /// 详情页那颗 6（padding 8/3）—— 同一个视觉角色、两个值，当年各写各的。
  /// `record_detail_page.dart` 的注释一直写着两处「用同一对色」是**故意的**，
  /// 但圆角与内边距没跟着一起定。2026-10-07 迁 P1 时查出，报给需求方后
  /// **当天裁定统一在 4**（小的那个值），6 那支已删。
  ///
  /// ⚠️ **内边距没有一起统一**（列表 6/2、详情 8/3 照旧）：P1 的范围是「只补圆角」，
  /// 间距有意不做。所以这两颗小标现在**圆角同、大小仍不同**，那是现状不是遗漏。
  ///
  /// ⚠️ 别为了「详情页那颗更小一点」再加一支 `tagXxx` —— 那正是这次要消掉的东西。
  /// 真需要第三颗不一样的小标，先问需求方，别在调用点写数字。
  static const tag = 4.0;
}
