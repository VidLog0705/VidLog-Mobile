/// VidLog 手机端 —— 三个显式建模的状态机（规格 §4）。
///
/// 规格明确要求「必须显式建模，不能靠 if 堆出来」，这三条是最容易出错的地方。
/// 与电脑端 `VidLog.Desktop.Core/States.cs` 一一对应。
library;

/// 录制会话状态。规格 §4.1。
///
/// 转移表：
/// ```
/// 空闲 ──识别到单号──────> 录制中
/// 录制中 ──手动停止──────> 收尾中
/// 录制中 ──同码复扫──────> 收尾中
/// 录制中 ──静止超时──────> 收尾中
/// 录制中 ──时长兜底──────> 收尾中
/// 录制中 ──进程被杀/掉电──> (重启后) 孤儿收尾 ──> 已入库
/// 收尾中 ──校验通过──────> 已入库 ──> 进入上传队列
/// 收尾中 ──成品校验失败──> 收尾失败
/// ```
/// 不变量 I9：任何进入「收尾中」的路径都必须走同一套收尾逻辑，不得有旁路。
enum RecordingSessionState {
  /// 空闲 —— 尚未识别到单号。
  idle,

  /// 录制中。
  recording,

  /// 收尾中 —— 封文件、算哈希、写索引。
  finalizing,

  /// 已入库，等待进入上传队列。
  indexed,

  /// 成品校验失败。规格 §4.1：不得当作正常入库。
  finalizeFailed,
}

/// 上传任务状态。规格 §4.2。
///
/// 约束：
/// - [failed] 必须是用户可见的状态（不变量 I3，禁止静默失败）。
/// - 只有 [archived] 才可能进入「可清理」。
/// - 进程重启后 [uploading] 必须能回到 [pending]，不能卡死。
enum UploadState {
  /// 待上传。
  pending,

  /// 上传中。
  uploading,

  /// 可重试失败后的等待退避期（有限次）。
  backoff,

  /// 已归档 —— 接收方明确回执且内容校验通过。
  archived,

  /// 上传失败 —— 不可重试失败或重试耗尽，用户可见且可手动重试。
  failed,
}

/// 证据生命周期状态。规格 §4.3。
enum EvidenceState {
  /// 活跃。
  active,

  /// 已锁定 —— 用户标记为争议，永不被自动清理（规格 §3.6.5）。
  locked,

  /// 待清理 —— 归档成功且超过保留期。
  cleanupPending,

  /// 已清理 —— 回查归档层通过后才允许到达此状态。
  cleaned,

  /// 归档缺失 —— 回查归档层不通过。规格 §3.5.4：
  /// 绝不删除本地副本，并告警（不变量 I8）。
  archiveMissing,
}
